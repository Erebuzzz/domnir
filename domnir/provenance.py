"""Server-side controller provenance.

When the server generates a controller through Vultr inference it records an
artifact: the exact source hash plus the model the inference API reported.
Later runs resolve provenance by artifact ID on the server, so a client cannot
obtain "generated by model X" by editing a JSON field.

Statuses:
* ``BUILT_IN_BASELINE``           server-side baseline controller.
* ``SERVER_CONFIRMED_GENERATION`` artifact found and the submitted source hash
                                  matches the generated source exactly.
* ``USER_MODIFIED``               artifact found but the source was changed.
* ``UNVERIFIED_ORIGIN``           no artifact (unknown ID, none supplied, or
                                  the server restarted and lost its registry).

The registry is in memory and bounded. It proves what this server generated;
it is not a signature that a third party can check offline.
"""

from __future__ import annotations

import hashlib
import threading
import uuid
from collections import OrderedDict
from dataclasses import asdict, dataclass
from datetime import datetime, timezone
from typing import Any

MAX_ARTIFACTS = 500

BUILT_IN_BASELINE = "BUILT_IN_BASELINE"
SERVER_CONFIRMED_GENERATION = "SERVER_CONFIRMED_GENERATION"
USER_MODIFIED = "USER_MODIFIED"
UNVERIFIED_ORIGIN = "UNVERIFIED_ORIGIN"


@dataclass(frozen=True)
class ControllerArtifact:
    artifact_id: str
    source_sha256: str
    model_id: str
    requested_model: str
    prompt_version: str
    reasoning_effort: str
    inference_provider: str
    finish_reason: str | None
    system_fingerprint: str | None
    prompt_tokens: int
    completion_tokens: int
    created_at: str

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


@dataclass(frozen=True)
class ProvenanceResolution:
    status: str
    model_id: str | None
    model_id_source: str
    artifact: ControllerArtifact | None

    def to_dict(self) -> dict[str, Any]:
        return {
            "status": self.status,
            "model_id": self.model_id,
            "model_id_source": self.model_id_source,
            "artifact": self.artifact.to_dict() if self.artifact else None,
        }


class ControllerArtifactRegistry:
    def __init__(self, max_artifacts: int = MAX_ARTIFACTS) -> None:
        self.max_artifacts = max_artifacts
        self._lock = threading.Lock()
        self._artifacts: OrderedDict[str, ControllerArtifact] = OrderedDict()

    def register(
        self,
        *,
        source_code: str,
        model_id: str,
        requested_model: str,
        prompt_version: str,
        reasoning_effort: str,
        inference_provider: str = "vultr-serverless-inference",
        finish_reason: str | None = None,
        system_fingerprint: str | None = None,
        prompt_tokens: int = 0,
        completion_tokens: int = 0,
    ) -> ControllerArtifact:
        artifact = ControllerArtifact(
            artifact_id=f"ctrl-{uuid.uuid4().hex}",
            source_sha256=hashlib.sha256(source_code.encode("utf-8")).hexdigest(),
            model_id=model_id,
            requested_model=requested_model,
            prompt_version=prompt_version,
            reasoning_effort=reasoning_effort,
            inference_provider=inference_provider,
            finish_reason=finish_reason,
            system_fingerprint=system_fingerprint,
            prompt_tokens=int(prompt_tokens or 0),
            completion_tokens=int(completion_tokens or 0),
            created_at=datetime.now(timezone.utc).isoformat(),
        )
        with self._lock:
            self._artifacts[artifact.artifact_id] = artifact
            while len(self._artifacts) > self.max_artifacts:
                self._artifacts.popitem(last=False)
        return artifact

    def get(self, artifact_id: str) -> ControllerArtifact | None:
        with self._lock:
            return self._artifacts.get(artifact_id)

    def resolve(
        self,
        source_code: str | None,
        artifact_id: str | None,
        client_model_id: str | None,
    ) -> ProvenanceResolution:
        if source_code is None:
            return ProvenanceResolution(BUILT_IN_BASELINE, "baseline_3d", "server", None)
        artifact = self.get(artifact_id) if artifact_id else None
        if artifact is None:
            return ProvenanceResolution(UNVERIFIED_ORIGIN, client_model_id, "client_reported", None)
        source_sha = hashlib.sha256(source_code.encode("utf-8")).hexdigest()
        if source_sha == artifact.source_sha256:
            return ProvenanceResolution(SERVER_CONFIRMED_GENERATION, artifact.model_id, "server_artifact", artifact)
        return ProvenanceResolution(USER_MODIFIED, artifact.model_id, "server_artifact_modified", artifact)


controller_artifacts = ControllerArtifactRegistry()
